#!/usr/bin/env node
/**
 * AUI Design System — Zero-Dependency Bundler (scripts/build.js)
 * Combines modular CSS in src/css/ and JS in src/js/ into:
 * - dist/aui.bundle.css
 * - dist/aui.bundle.js
 * - templates/single-file-starter.html (Self-contained single-file template)
 *
 * Flags:
 *   --check   Verify generated artifacts match current src/ without writing
 *   --minify  Also emit dist/aui.bundle.min.css and dist/aui.bundle.min.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS_ENTRY = path.join(ROOT, 'src', 'css', 'aui.css');

function resolveCssOrder() {
    const entryContent = fs.readFileSync(CSS_ENTRY, 'utf8');
    const files = [];
    const importRegex = /@import\s+url\(['"]\.\/([^'"]+)['"]\)\s*;/g;
    let match;
    while ((match = importRegex.exec(entryContent)) !== null) {
        files.push(match[1]);
    }
    if (files.length === 0) {
        throw new Error('No @import rules found in src/css/aui.css');
    }
    return files;
}

function minifyCss(css) {
    return css
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/\s+/g, ' ')
        .replace(/\s*([{}:;,>~])\s*/g, (m, ch) => (ch === ':' ? ': ' : ch))
        .replace(/:\s+/g, ':')
        .replace(/\s+:/g, ' :')
        .replace(/;}/g, '}')
        .trim() + '\n';
}

function minifyJs(js) {
    // Conservative zero-dependency line/comment stripper preserving strings & semantics
    const lines = js.split('\n');
    const out = [];
    let inBlockComment = false;
    for (const rawLine of lines) {
        const trimmed = rawLine.trim();
        if (!trimmed) continue;
        if (inBlockComment) {
            if (trimmed.includes('*/')) inBlockComment = false;
            continue;
        }
        if (trimmed.startsWith('/*')) {
            if (!trimmed.includes('*/')) inBlockComment = true;
            continue;
        }
        if (trimmed.startsWith('//')) continue;
        out.push(trimmed);
    }
    return out.join('\n') + '\n';
}

function computeOutputs() {
    const cssOrder = resolveCssOrder();
    const cssChunks = [
        '/* AUI Design System — Bundled Stylesheet (Auto-generated by scripts/build.js) */'
    ];
    for (const file of cssOrder) {
        const filePath = path.join(ROOT, 'src', 'css', file);
        const content = fs.readFileSync(filePath, 'utf8');
        cssChunks.push(`/* === ${file} === */\n${content.trim()}`);
    }
    const bundledCss = cssChunks.join('\n\n') + '\n';
    if (/<\/style>/i.test(bundledCss)) {
        throw new Error('Bundled CSS contains closing </style> tag which cannot be safely inlined.');
    }

    const bundledJs = fs.readFileSync(path.join(ROOT, 'src', 'js', 'aui-core.js'), 'utf8');
    if (/<\/script>/i.test(bundledJs)) {
        throw new Error('Bundled JS contains closing </script> tag which cannot be safely inlined.');
    }

    const modularHtml = fs.readFileSync(path.join(ROOT, 'templates', 'modular-starter.html'), 'utf8');
    const cssLinkTag = '<link rel="stylesheet" href="../src/css/aui.css">';
    const jsScriptTag = '<script src="../src/js/aui-core.js"></script>';

    if (!modularHtml.includes(cssLinkTag)) {
        throw new Error(`Expected CSS link placeholder not found in modular-starter.html: ${cssLinkTag}`);
    }
    if (!modularHtml.includes(jsScriptTag)) {
        throw new Error(`Expected JS script placeholder not found in modular-starter.html: ${jsScriptTag}`);
    }

    const singleFileHtml = modularHtml
        .replace(cssLinkTag, () => `<style>\n${bundledCss}</style>`)
        .replace(jsScriptTag, () => `<script>\n${bundledJs}</script>`);

    return { bundledCss, bundledJs, singleFileHtml };
}

function main() {
    const args = process.argv.slice(2);
    const checkOnly = args.includes('--check');
    const emitMinify = args.includes('--minify');
    const { bundledCss, bundledJs, singleFileHtml } = computeOutputs();

    const targets = [
        { rel: 'dist/aui.bundle.css', content: bundledCss },
        { rel: 'dist/aui.bundle.js', content: bundledJs },
        { rel: 'templates/single-file-starter.html', content: singleFileHtml }
    ];

    if (emitMinify) {
        targets.push(
            { rel: 'dist/aui.bundle.min.css', content: minifyCss(bundledCss) },
            { rel: 'dist/aui.bundle.min.js', content: minifyJs(bundledJs) }
        );
    }

    if (checkOnly) {
        const stale = [];
        for (const t of targets) {
            const abs = path.join(ROOT, t.rel);
            const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
            if (current !== t.content) stale.push(t.rel);
        }
        if (stale.length > 0) {
            console.error('[AUI Check] Out-of-sync artifacts detected:', stale.join(', '));
            process.exit(1);
        }
        console.log('[AUI Check] All bundled artifacts are up to date.');
        return;
    }

    const distDir = path.join(ROOT, 'dist');
    if (!fs.existsSync(distDir)) {
        fs.mkdirSync(distDir, { recursive: true });
    }

    console.log('[AUI Build] Successfully generated:');
    for (const t of targets) {
        const abs = path.join(ROOT, t.rel);
        fs.writeFileSync(abs, t.content, 'utf8');
        console.log(`  - ${t.rel} (${Buffer.byteLength(t.content)} bytes)`);
    }
}

main();
