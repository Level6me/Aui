#!/usr/bin/env node
/**
 * AUI Design System — Zero-Dependency Bundler (scripts/build.js)
 * Combines modular CSS in src/css/ and JS in src/js/ into:
 * - dist/aui.bundle.css
 * - dist/aui.bundle.js
 * - templates/single-file-starter.html (Self-contained single-file template)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS_ORDER = [
    'variables.css',
    'base.css',
    'layout.css',
    'components.css',
    'data-display.css',
    'dock.css',
    'modal.css'
];

function build() {
    const distDir = path.join(ROOT, 'dist');
    if (!fs.existsSync(distDir)) {
        fs.mkdirSync(distDir, { recursive: true });
    }

    const cssChunks = [
        '/* AUI Design System — Bundled Stylesheet (Auto-generated by scripts/build.js) */'
    ];
    for (const file of CSS_ORDER) {
        const filePath = path.join(ROOT, 'src', 'css', file);
        const content = fs.readFileSync(filePath, 'utf8');
        cssChunks.push(`/* === ${file} === */\n${content.trim()}`);
    }
    const bundledCss = cssChunks.join('\n\n') + '\n';
    fs.writeFileSync(path.join(distDir, 'aui.bundle.css'), bundledCss, 'utf8');

    const bundledJs = fs.readFileSync(path.join(ROOT, 'src', 'js', 'aui-core.js'), 'utf8');
    fs.writeFileSync(path.join(distDir, 'aui.bundle.js'), bundledJs, 'utf8');

    // Generate Single-File Starter from modular-starter.html
    const modularHtml = fs.readFileSync(path.join(ROOT, 'templates', 'modular-starter.html'), 'utf8');
    const singleFileHtml = modularHtml
        .replace('<link rel="stylesheet" href="../src/css/aui.css">', `<style>\n${bundledCss}</style>`)
        .replace('<script src="../src/js/aui-core.js"></script>', `<script>\n${bundledJs}</script>`);
    fs.writeFileSync(path.join(ROOT, 'templates', 'single-file-starter.html'), singleFileHtml, 'utf8');

    console.log('[AUI Build] Successfully generated:');
    console.log('  - dist/aui.bundle.css (' + Buffer.byteLength(bundledCss) + ' bytes)');
    console.log('  - dist/aui.bundle.js (' + Buffer.byteLength(bundledJs) + ' bytes)');
    console.log('  - templates/single-file-starter.html (' + Buffer.byteLength(singleFileHtml) + ' bytes)');
}

build();
